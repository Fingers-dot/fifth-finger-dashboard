    if (!currentMapCode || currentMapCode === 'HEAT') {
      if (pickedOrigin && pickedOrigin.includes('티손')) selectMapNation('TS');
      else if (pickedOrigin && pickedOrigin.includes('카른')) selectMapNation('KR');
      else if (pickedOrigin && pickedOrigin.includes('르니그')) selectMapNation('RN');
      else if (pickedOrigin && pickedOrigin.includes('아티스')) selectMapNation('AT');
      else selectMapNation('HEAT');
    }

