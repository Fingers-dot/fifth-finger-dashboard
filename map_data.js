  /* Pan & Zoom 변환 적용 */
  function applyMapTransform() {
    const layer = document.getElementById('map-transform-layer');
    const badge = document.getElementById('map-zoom-scale-badge');
    if (layer) {
      layer.style.transform = `translate(${mapPanX}px, ${mapPanY}px) scale(${mapScale})`;
    }
    if (badge) {
      badge.innerText = `${Math.round(mapScale * 100)}%`;
    }
  }

  function resetMapPanZoom() {
    const viewport = document.getElementById('map-viewport');
    const img = document.getElementById('map-display-image');
    mapScale = 1.0;
    if (viewport && img && img.naturalWidth) {
      const vRect = viewport.getBoundingClientRect();
      mapPanX = (vRect.width - img.naturalWidth) / 2;
      mapPanY = (vRect.height - img.naturalHeight) / 2;
    } else {
      mapPanX = 0; mapPanY = 0;
    }
    applyMapTransform();
  }

  function adjustMapZoom(factor) {
    const viewport = document.getElementById('map-viewport');
    const newScale = Math.max(0.05, Math.min(5.0, mapScale * factor));
    if (viewport) {
      const rect = viewport.getBoundingClientRect();
      const centerX = rect.width / 2;
      const centerY = rect.height / 2;
      mapPanX = centerX - (centerX - mapPanX) * (newScale / mapScale);
      mapPanY = centerY - (centerY - mapPanY) * (newScale / mapScale);
    }
    mapScale = newScale;
    applyMapTransform();
  }

  function fitMapToViewport() {
    const viewport = document.getElementById('map-viewport');
    const img = document.getElementById('map-display-image');
    if (!viewport || !img || !img.naturalWidth || img.naturalWidth <= 0) return;

    const vRect = viewport.getBoundingClientRect();
    if (vRect.width <= 0 || vRect.height <= 0) {
      setTimeout(fitMapToViewport, 40);
      return;
    }

    const scaleX = (vRect.width - 40) / img.naturalWidth;
    const scaleY = (vRect.height - 40) / img.naturalHeight;
    // 여백 20px를 남기고 전체 이미지가 뷰포트 안에 100% 들어오도록 자동 축소 (최소 5%까지 허용)
    mapScale = Math.max(0.05, Math.min(1.0, Math.min(scaleX, scaleY)));

    mapPanX = (vRect.width - (img.naturalWidth * mapScale)) / 2;
    mapPanY = (vRect.height - (img.naturalHeight * mapScale)) / 2;
    applyMapTransform();
  }

  function handleMapWheel(e) {
    e.preventDefault();
    const zoomFactor = e.deltaY < 0 ? 1.15 : 0.87;
    const newScale = Math.max(0.05, Math.min(5.0, mapScale * zoomFactor));

    const viewport = document.getElementById('map-viewport');
    if (viewport) {
      const rect = viewport.getBoundingClientRect();
      const mouseX = e.clientX - rect.left;
      const mouseY = e.clientY - rect.top;

      mapPanX = mouseX - (mouseX - mapPanX) * (newScale / mapScale);
      mapPanY = mouseY - (mouseY - mapPanY) * (newScale / mapScale);
    }
    mapScale = newScale;
    applyMapTransform();
  }

  function handleMapMouseDown(e) {
    if (e.button !== 0) return;
    isMapDragging = true;
    mapDidDrag = false;
    mapDragStartX = e.clientX - mapPanX;
    mapDragStartY = e.clientY - mapPanY;
    mapDragInitX = e.clientX;
    mapDragInitY = e.clientY;

    window.addEventListener('mousemove', handleMapMouseMove);
    window.addEventListener('mouseup', handleMapMouseUp, { once: true });
  }

  function handleMapMouseMove(e) {
    if (!isMapDragging) return;
    const dx = e.clientX - mapDragInitX;
    const dy = e.clientY - mapDragInitY;
    if (Math.hypot(dx, dy) > 4) {
      mapDidDrag = true;
    }
    mapPanX = e.clientX - mapDragStartX;
    mapPanY = e.clientY - mapDragStartY;
    applyMapTransform();
  }

  function handleMapMouseUp() {
    if (mapDidDrag) {
      // 드래그 후 250ms 동안 클릭으로 인한 모달 닫힘을 원천 차단
      suppressMapModalCloseUntil = Date.now() + 250;
    }
    isMapDragging = false;
    window.removeEventListener('mousemove', handleMapMouseMove);
  }

  /* 모바일/태블릿 터치 제스처 드래그 지원 */
  let touchStartPanX = 0, touchStartPanY = 0;
  let touchStartX = 0, touchStartY = 0;
  let isTouchDragging = false;

  function handleMapTouchStart(e) {
    if (e.touches.length === 1) {
      isTouchDragging = true;
      mapDidDrag = false;
      touchStartX = e.touches[0].clientX;
      touchStartY = e.touches[0].clientY;
      touchStartPanX = mapPanX;
      touchStartPanY = mapPanY;
    }
  }

  function handleMapTouchMove(e) {
    if (!isTouchDragging || e.touches.length !== 1) return;
    e.preventDefault();
    const dx = e.touches[0].clientX - touchStartX;
    const dy = e.touches[0].clientY - touchStartY;
    if (Math.hypot(dx, dy) > 4) {
      mapDidDrag = true;
    }
    mapPanX = touchStartPanX + dx;
    mapPanY = touchStartPanY + dy;
    applyMapTransform();
  }

  function handleMapTouchEnd() {
    if (mapDidDrag) {
      suppressMapModalCloseUntil = Date.now() + 250;
    }
    isTouchDragging = false;
  }

  /* 노드 인스펙터 렌더링 & 필터링 */
  function renderNodeList(regionObj) {
    const listEl = document.getElementById('node-list-container');
    const titleEl = document.getElementById('sidebar-region-title');
    const countEl = document.getElementById('sidebar-node-count');
    const searchInput = document.getElementById('map-node-search');

    if (titleEl) titleEl.innerText = `📍 [${regionObj.code}] ${regionObj.name}`;
    if (searchInput) searchInput.value = '';
    currentNodeFilter = 'all';

    filterNodeList();
  }

  function filterNodeList() {
    const regionObj = MAP_REGIONS_DATA[currentMapCode];
    if (!regionObj) return;

    const listEl = document.getElementById('node-list-container');
    const countEl = document.getElementById('sidebar-node-count');
    const query = (document.getElementById('map-node-search').value || '').trim().toLowerCase();

    let filtered = regionObj.nodes.filter(n => {
      const matchText = (n.id + n.name + n.terrain + (n.desc || '')).toLowerCase().includes(query);
      if (!matchText) return false;

      if (currentNodeFilter === 'camp') return n.camp;
      if (currentNodeFilter === 'town') return n.isTown;
      if (currentNodeFilter === 'event') return n.isEvent;
      return true;
    });

    if (countEl) countEl.innerText = `${filtered.length}개 노드`;
    if (!listEl) return;

    listEl.innerHTML = filtered.map(n => {
      const isSelected = selectedNodeObj && selectedNodeObj.id === n.id;
      const formattedConns = (n.conns || '외길').replace(/\n/g, '<br>');
      return `
        <div class="node-card ${isSelected ? 'selected' : ''}" onclick="selectNodeCard('${n.id}')">
          <div class="node-header-row">
            <span class="node-id-badge">${n.id}</span>
            <span class="node-name-text">${n.name}</span>
            <span style="font-size:10px; margin-left:auto; display:inline-flex; align-items:center; gap:5px;">
              <span>${n.camp ? '🏕️' : '⚠️'}</span>
              <span class="node-accordion-chevron">${isSelected ? '▴' : '▾'}</span>
            </span>
          </div>
          <div class="node-body-details">
            <div class="node-terrain-tag" style="color:#7dd3fc; line-height:1.4;">${n.terrain}</div>
            <div class="node-conns-row" style="align-items:flex-start; margin-top:2px;">
              <span style="color:#60a5fa; font-weight:700; flex-shrink:0;">연결:</span>
              <span style="line-height:1.45; font-size:10px; color:#cbd5e1;">${formattedConns}</span>
            </div>
            ${n.desc ? `<div class="node-desc-box">${n.desc}</div>` : ''}
          </div>
        </div>
      `;
    }).join('');
  }

  function setNodeFilter(filterType, btn) {
    currentNodeFilter = filterType;
    document.querySelectorAll('.node-chip-btn').forEach(b => b.classList.remove('active'));
    if (btn) btn.classList.add('active');
    filterNodeList();
    playBeep(480, 'sine', 0.05);
  }

  function selectNodeCard(nodeId) {
    const reg = MAP_REGIONS_DATA[currentMapCode];
    if (!reg) return;
    const node = reg.nodes.find(n => n.id === nodeId);
    if (!node) return;

    // 클릭 시 선택 토글 하이라이트
    selectedNodeObj = (selectedNodeObj && selectedNodeObj.id === node.id) ? null : node;
    playBeep(580, 'sine', 0.08);
    filterNodeList();
  }